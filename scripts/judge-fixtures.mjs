// A3/A4 (credit-funded judging + free aggregation): for every built eval fixture,
// send Azure Foundry the intended document spec and the converter's ACTUAL
// Markdown, and ask it to (a) produce an "ideal" GFM rendering, (b) score
// fidelity 0-1, and (c) list concrete issues. Raw judgments are dumped to
// .gen-cache/judgments/ before aggregation; the digest is written to
// docs/converter-quality-report.md as a prioritized improvement roadmap.
//
// Run (after build-fixtures.mjs): node scripts/judge-fixtures.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { chatJson, dumpRaw } from './lib/azure.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SPEC_DIR = path.join(__dirname, '.gen-cache', 'specs');
const JUDGE_DIR = path.join(__dirname, '.gen-cache', 'judgments');
const EVAL_DIR = path.join(__dirname, '..', 'src', '__fixtures__', 'eval');
const REPORT = path.join(
  __dirname,
  '..',
  'docs',
  'converter-quality-report.md',
);

const SYSTEM = `You are a meticulous evaluator of a Word (.docx) → Markdown converter.
You are given (1) the INTENDED document as a structured spec and (2) the converter's ACTUAL Markdown output.
Judge how faithfully the actual output represents the intended document in clean GitHub-Flavored Markdown.
Return ONLY JSON:
{
  "score": <number 0..1, 1 = perfect fidelity>,
  "idealMarkdown": "<the ideal GFM you'd expect for this document>",
  "issues": [ {"severity":"high|medium|low","description":"<specific, actionable problem>"} ]
}
Focus on real fidelity problems (broken tables, lost content, wrong list numbering, mangled inline styles). An empty issues array means the output is correct.`;

const SEV_RANK = { high: 0, medium: 1, low: 2 };

async function main() {
  const manifestPath = path.join(EVAL_DIR, 'manifest.json');
  if (!fs.existsSync(manifestPath)) {
    throw new Error(
      `No manifest at ${manifestPath}. Run build-fixtures.mjs first.`,
    );
  }
  fs.mkdirSync(JUDGE_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(REPORT), { recursive: true });

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const results = [];
  for (const { name, description } of manifest) {
    const specPath = path.join(SPEC_DIR, `${name}.json`);
    const mdPath = path.join(EVAL_DIR, `${name}.md`);
    if (!fs.existsSync(specPath) || !fs.existsSync(mdPath)) {
      console.warn(`✗ ${name}: missing spec or markdown, skipping`);
      continue;
    }
    const spec = fs.readFileSync(specPath, 'utf8');
    const actual = fs.readFileSync(mdPath, 'utf8');
    try {
      const { parsed, raw } = await chatJson({
        messages: [
          { role: 'system', content: SYSTEM },
          {
            role: 'user',
            content: `INTENDED SPEC:\n${spec}\n\nACTUAL MARKDOWN OUTPUT:\n\`\`\`\n${actual}\n\`\`\``,
          },
        ],
        temperature: 0.2,
        maxTokens: 2000,
      });
      dumpRaw(path.join(JUDGE_DIR, `${name}.raw.json`), raw);
      dumpRaw(path.join(JUDGE_DIR, `${name}.json`), parsed);
      results.push({ name, description, ...parsed });
      console.log(`✓ ${name} — score ${Number(parsed.score).toFixed(2)}`);
    } catch (err) {
      console.warn(`✗ ${name}: ${err.message}`);
    }
  }

  writeReport(results);
  const avg =
    results.reduce((s, r) => s + (Number(r.score) || 0), 0) /
    (results.length || 1);
  console.log(
    `\nJudged ${results.length} fixture(s); mean fidelity ${avg.toFixed(2)}.\n` +
      `Report: ${path.relative(process.cwd(), REPORT)}`,
  );
}

function writeReport(results) {
  const sorted = [...results].sort((a, b) => (a.score ?? 1) - (b.score ?? 1));
  const allIssues = results.flatMap((r) =>
    (r.issues ?? []).map((i) => ({ ...i, fixture: r.name })),
  );
  allIssues.sort(
    (a, b) => (SEV_RANK[a.severity] ?? 3) - (SEV_RANK[b.severity] ?? 3),
  );
  const mean =
    results.reduce((s, r) => s + (Number(r.score) || 0), 0) /
    (results.length || 1);

  const counts = { high: 0, medium: 0, low: 0 };
  for (const i of allIssues) counts[i.severity] = (counts[i.severity] ?? 0) + 1;

  const lines = [];
  lines.push('# Converter quality report');
  lines.push('');
  lines.push(
    '> Generated by an LLM judge over the adversarial eval corpus ' +
      '(`scripts/judge-fixtures.mjs`). Each fixture pairs an intended document ' +
      'spec with the converter’s actual Markdown; the judge scores fidelity and ' +
      'lists concrete issues. This is a prioritized backlog of real converter ' +
      'deficiencies, not a pass/fail gate.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- Fixtures judged: **${results.length}**`);
  lines.push(`- Mean fidelity score: **${mean.toFixed(2)}** / 1.00`);
  lines.push(
    `- Issues: **${counts.high} high**, **${counts.medium} medium**, **${counts.low} low**`,
  );
  lines.push('');
  lines.push('## Top issues (by severity)');
  lines.push('');
  if (allIssues.length === 0) {
    lines.push('_No issues found._');
  } else {
    for (const i of allIssues) {
      lines.push(`- **[${i.severity}]** (${i.fixture}) ${i.description}`);
    }
  }
  lines.push('');
  lines.push('## Per-fixture scores (lowest first)');
  lines.push('');
  lines.push('| Fixture | Score | Challenge |');
  lines.push('| --- | --- | --- |');
  for (const r of sorted) {
    lines.push(
      `| \`${r.name}\` | ${Number(r.score ?? 0).toFixed(2)} | ${(r.description ?? '').replace(/\|/g, '\\|')} |`,
    );
  }
  lines.push('');
  fs.writeFileSync(REPORT, `${lines.join('\n')}\n`);
}

await main();
